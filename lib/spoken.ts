// Голосовая запись: распознавание речи иногда отдаёт числа словами — переводим в цифры.

/** Слова-числа, которые иногда приходят из распознавания речи вместо цифр. */
const NUM_WORDS: Record<string, number> = {
  ноль: 0, один: 1, одна: 1, два: 2, две: 2, три: 3, четыре: 4, пять: 5, шесть: 6, семь: 7, восемь: 8, девять: 9, десять: 10,
  одиннадцать: 11, двенадцать: 12, тринадцать: 13, четырнадцать: 14, пятнадцать: 15, шестнадцать: 16, семнадцать: 17, восемнадцать: 18, девятнадцать: 19,
  двадцать: 20, тридцать: 30, сорок: 40, пятьдесят: 50, шестьдесят: 60, семьдесят: 70, восемьдесят: 80, девяносто: 90,
  сто: 100, двести: 200, триста: 300, четыреста: 400, пятьсот: 500, шестьсот: 600, семьсот: 700, восемьсот: 800, девятьсот: 900,
};
const THOUSAND = /^тысяч[аи]?$/;

/** «кофе семьдесят пять гривен» → «кофе 75». Цифры, которые уже пришли цифрами, не трогаем. */
export function spokenToText(s: string): string {
  const out: string[] = [];
  let num: number | null = null;
  let part = 0;
  const flush = () => {
    if (num !== null || part) out.push(String((num ?? 0) + part));
    num = null;
    part = 0;
  };
  for (const raw of s.toLowerCase().replace(/ё/g, "е").split(/\s+/)) {
    const w = raw.replace(/[.,!?]/g, "");
    if (Object.hasOwn(NUM_WORDS, w)) part += NUM_WORDS[w];
    else if (THOUSAND.test(w)) {
      num = (num ?? 0) + (part || 1) * 1000;
      part = 0;
    } else if (/^(гривен|гривны|гривна|грн)$/.test(w)) flush();
    else {
      flush();
      if (w) out.push(raw);
    }
  }
  flush();
  return out.join(" ").replace(/(\d)\s+(\d{3})\b/g, "$1$2");
}

